#![allow(dead_code)]

use crate::ast::*;
use std::fs;
use std::path::Path;

#[derive(Debug, Clone)]
pub struct DocItem {
    pub name: String,
    pub doc_comment: String,
    pub signature: String,
    pub item_type: String, // "function", "struct", "enum", "trait", "module"
}

pub fn extract_doc_comments(source: &str) -> Vec<(String, String)> {
    let mut comments = Vec::new();
    let mut current_doc = Vec::new();

    for line in source.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("///") {
            current_doc.push(trimmed.trim_start_matches("///").trim().to_string());
        } else if (trimmed.starts_with("fn ") || trimmed.starts_with("struct ") || trimmed.starts_with("enum ") || trimmed.starts_with("trait ")) && !current_doc.is_empty() {
            let name = trimmed.split_whitespace().nth(1).unwrap_or("").split('(').next().unwrap_or("").to_string();
            comments.push((name, current_doc.join("\n")));
            current_doc.clear();
        } else if !trimmed.is_empty() && !trimmed.starts_with("//") {
            current_doc.clear();
        }
    }
    comments
}

pub fn generate_html_docs(program: &Program, source: &str, project_name: &str, output_dir: &Path) -> std::io::Result<()> {
    let doc_map = extract_doc_comments(source);
    let get_doc = |name: &str| -> String {
        for (n, d) in &doc_map {
            if n == name {
                return d.clone();
            }
        }
        "No documentation provided.".to_string()
    };

    let modules_dir = output_dir.join("modules");
    let structs_dir = output_dir.join("structs");
    let functions_dir = output_dir.join("functions");
    let traits_dir = output_dir.join("traits");

    fs::create_dir_all(&modules_dir)?;
    fs::create_dir_all(&structs_dir)?;
    fs::create_dir_all(&functions_dir)?;
    fs::create_dir_all(&traits_dir)?;

    let mut functions = Vec::new();
    let mut structs = Vec::new();
    let mut enums = Vec::new();

    for stmt in &program.statements {
        match &stmt.kind {
            StmtKind::Function { name, is_async, params, ret_type, .. } => {
                let async_badge = if *is_async { "async " } else { "" };
                let p_strs: Vec<String> = params.iter().map(|(p, t)| format!("{}: {:?}", p, t)).collect();
                let sig = format!("{}fn {}({}) -> {:?}", async_badge, name, p_strs.join(", "), ret_type);
                let doc = get_doc(name);
                functions.push((name.clone(), sig, doc));
            }
            StmtKind::StructDecl { name, fields, .. } => {
                let mut sig = format!("struct {} {{\n", name);
                for (f, t) in fields {
                    sig.push_str(&format!("    {}: {:?},\n", f, t));
                }
                sig.push_str("}");
                let doc = get_doc(name);
                structs.push((name.clone(), sig, doc));
            }
            StmtKind::EnumDecl { name, variants, .. } => {
                let mut sig = format!("enum {} {{\n", name);
                for (v, p) in variants {
                    if let Some(payload) = p {
                        sig.push_str(&format!("    {}({:?}),\n", v, payload));
                    } else {
                        sig.push_str(&format!("    {},\n", v));
                    }
                }
                sig.push_str("}");
                let doc = get_doc(name);
                enums.push((name.clone(), sig, doc));
            }
            _ => {}
        }
    }

    // 1. Generate index.html
    let mut index_html = String::new();
    index_html.push_str(&render_html_header(&format!("API Reference - {}", project_name)));
    index_html.push_str(&format!("<h1>🌌 {} Documentation</h1>\n", project_name));
    index_html.push_str("<p class='lead'>Fast, Safe, Elegant & High-Performance Language Reference generated by <code>sorayunara doc</code>.</p>\n<hr/>\n");

    index_html.push_str("<h2>⚡ Functions</h2>\n<ul class='item-list'>\n");
    for (name, sig, doc) in &functions {
        index_html.push_str(&format!("<li><a href='functions/{}.html'><code>{}</code></a> — <span class='summary'>{}</span></li>\n", name, name, doc.lines().next().unwrap_or("")));
        let fn_page = render_item_page(name, "Function", sig, doc, "../index.html");
        fs::write(functions_dir.join(format!("{}.html", name)), fn_page)?;
    }
    index_html.push_str("</ul>\n");

    index_html.push_str("<h2>📦 Structs</h2>\n<ul class='item-list'>\n");
    for (name, sig, doc) in &structs {
        index_html.push_str(&format!("<li><a href='structs/{}.html'><code>{}</code></a> — <span class='summary'>{}</span></li>\n", name, name, doc.lines().next().unwrap_or("")));
        let struct_page = render_item_page(name, "Struct", sig, doc, "../index.html");
        fs::write(structs_dir.join(format!("{}.html", name)), struct_page)?;
    }
    index_html.push_str("</ul>\n");

    index_html.push_str(&render_html_footer());
    fs::write(output_dir.join("index.html"), index_html)?;

    // Create index stubs for modules/ and traits/
    let mod_index = render_section_index("Modules", "Available Sorayunara standard and application modules", &[]);
    fs::write(modules_dir.join("index.html"), mod_index)?;

    let traits_index = render_section_index("Traits & Interfaces", "Sorayunara type traits and interface contracts", &[]);
    fs::write(traits_dir.join("index.html"), traits_index)?;

    Ok(())
}

