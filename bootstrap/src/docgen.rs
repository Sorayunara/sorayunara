fn render_item_page(name: &str, kind: &str, signature: &str, doc: &str, back_href: &str) -> String {
    let mut s = String::new();
    s.push_str(&render_html_header(&format!("{} {} - Aether Docs", kind, name)));
    s.push_str(&format!("<a class='back-link' href='{}'>← Back to Overview</a>\n", back_href));
    s.push_str(&format!("<h1>{} <code>{}</code></h1>\n", kind, name));
    s.push_str("<h3>Declaration</h3>\n");
    s.push_str(&format!("<pre><code>{}</code></pre>\n", signature));
    s.push_str("<h3>Documentation</h3>\n");
    s.push_str(&format!("<div class='doc-section'>{}</div>\n", doc));
    s.push_str(&render_html_footer());
    s
}

fn render_section_index(title: &str, desc: &str, items: &[String]) -> String {
    let mut s = String::new();
    s.push_str(&render_html_header(title));
    s.push_str("<a class='back-link' href='../index.html'>← Back to Overview</a>\n");
    s.push_str(&format!("<h1>{}</h1>\n<p>{}</p>\n", title, desc));
    s.push_str("<ul class='item-list'>\n");
    if items.is_empty() {
        s.push_str("<li><em>No items registered yet.</em></li>\n");
    } else {
        for it in items {
            s.push_str(&format!("<li>{}</li>\n", it));
        }
    }
    s.push_str("</ul>\n");
    s.push_str(&render_html_footer());
    s
}

pub fn generate_docs(program: &Program, project_name: &str) -> String {
    let mut doc = String::new();
    doc.push_str(&format!("# API Documentation: {}\n\n", project_name));
    doc.push_str("Generated by `aether doc` toolchain.\n\n---\n\n");

    let mut structs = Vec::new();
    let mut enums = Vec::new();
    let mut functions = Vec::new();

    for stmt in &program.statements {
        match &stmt.kind {
            StmtKind::StructDecl { name, fields, .. } => structs.push((name, fields)),
            StmtKind::EnumDecl { name, variants, .. } => enums.push((name, variants)),
            StmtKind::Function {
                name,
                is_async,
                params,
                ret_type,
                ..
            } => functions.push((name, is_async, params, ret_type)),
            _ => {}
        }
    }

    if !functions.is_empty() {
        doc.push_str("## ⚡ Functions\n\n");
        for (name, is_async, params, ret_type) in functions {
            let async_badge = if *is_async { "`async` " } else { "" };
            let p_strs: Vec<String> = params.iter().map(|(p, t)| format!("{}: {:?}", p, t)).collect();
            doc.push_str(&format!("### {}`fn {}({}) -> {:?}`\n\n", async_badge, name, p_strs.join(", "), ret_type));
        }
    }

    if !structs.is_empty() {
        doc.push_str("## 📦 Structs\n\n");
        for (name, fields) in structs {
            doc.push_str(&format!("### `struct {}`\n\n", name));
            doc.push_str("| Field | Type |\n|---|---|\n");
            for (f, t) in fields {
                doc.push_str(&format!("| `{}` | `{:?}` |\n", f, t));
            }
            doc.push_str("\n");
        }
    }

    doc
}
